import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'

async function openDisclosure(page, id) {
  const disclosure = page.locator(id)
  if (!(await disclosure.evaluate(element => element.open))) await disclosure.locator(':scope > summary').click()
}

async function setup(page) {
  await page.goto('/')
  await page.setInputFiles('#file-input', 'tests/fixtures/test-tone-8s.wav')
  await expect(page.locator('#export-btn')).toBeEnabled()
  await page.click('[data-mode="lyrics"]')
  await expect(page.locator('#lyrics-source')).toContainText('來源已連結')
  await page.locator('#lyrics-raw').fill('右だけ\n\n右だけ')
  await page.click('[data-command="lyrics.apply"]')
}
async function mark(page, row, start, end) {
  await page.locator(`[data-line="line-${row}"]`).click()
  await page.locator('#lyrics-start-value').fill(String(start)); await page.locator('#lyrics-start-value').press('Tab')
  await page.locator('#lyrics-end-value').fill(String(end)); await page.locator('#lyrics-end-value').press('Tab')
  await page.click('[data-command="lyrics.confirm"]')
}
async function downloaded(page, selector) {
  const pending = page.waitForEvent('download'); await page.click(selector)
  const file = await pending; return fs.readFile(await file.path(), 'utf8')
}
test('lyrics raw text, timing, undo/reopen and four real downloads', async ({ page }, testInfo) => {
  const errors = []; page.on('pageerror', err => errors.push(err.message))
  await setup(page)
  await mark(page, 1, 1, 2); await mark(page, 3, 4, 5)
  await page.click('[data-command="lyrics.undo"]')
  await expect(page.locator('#lyrics-diagnostics')).toContainText('尚未確認')
  await page.click('[data-command="lyrics.redo"]')
  await page.screenshot({ path: testInfo.outputPath('lyrics-desktop.png') })
  const project = await downloaded(page, '[data-command="lyrics.save"]')
  expect(JSON.parse(project).source.hash).toMatch(/^[a-f0-9]{64}$/)
  for (const format of ['txt', 'srt', 'lrc', 'ass']) {
    const text = await downloaded(page, `[data-command="lyrics.export.${format}"]`)
    expect(text).toContain('右だけ')
    if (format === 'txt') expect(text).toBe('右だけ\n\n右だけ')
    if (format === 'srt') expect(text).toContain('00:00:04,000 --> 00:00:05,000')
    if (format === 'lrc') expect(text).toContain('[00:02.00]\n[00:04.00]右だけ')
  }
  await page.reload(); await page.click('[data-mode="lyrics"]')
  await page.setInputFiles('#lyrics-project-file', { name: 'lyrics.json', mimeType: 'application/json', buffer: Buffer.from(project) })
  await expect(page.locator('#lyrics-source')).toContainText('來源未連結')
  await expect(page.locator('[data-command="lyrics.export.srt"]')).toBeDisabled()
  await page.setInputFiles('#file-input', 'tests/fixtures/test-tone-8s.wav')
  await expect(page.locator('#lyrics-source')).toContainText('來源已連結')
  expect(await downloaded(page, '[data-command="lyrics.export.srt"]')).toContain('00:00:04,000 --> 00:00:05,000')
  expect(errors).toEqual([])
})
