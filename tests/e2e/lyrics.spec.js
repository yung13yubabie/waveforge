test('autosave quota failure preserves editable memory and downloadable project', async ({ page }) => {
  await page.addInitScript(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key === 'waveforge.lyrics.recovery.v1') throw new DOMException('Quota exceeded', 'QuotaExceededError')
      return original.call(this, key, value)
    }
  })
  await setup(page); await mark(page, 1, 1, 2)
  await expect(page.locator('#lyrics-save-status')).toContainText('備份失敗')
  const project = JSON.parse(await downloaded(page, '[data-command="lyrics.save"]'))
  expect(project.lines[0].start).toBe(1); expect(project.lines[0].confirmed).toBe(true)
  await page.click('[data-command="lyrics.undo"]')
  await expect(page.locator('#lyrics-diagnostics')).toContainText('尚未確認')
})

